def finite(value):return isinstance(value,(int,float)) and not isinstance(value,bool) and math.isfinite(value)
def display(value):return str(value) if finite(value) else t('No estimable')
def short(value):return f'{value:.6g}' if finite(value) else t('No estimable')

def snapshot(folder,assay):
    """Read one cached workbook snapshot and validate its publication provenance."""
    l=Layout(folder);report=json.loads((l.meta/'status.json').read_text(encoding='utf-8'))
    if report.get('excel_sha256')!=file_hash(l.master):return dict(state='stale_excel')
    state=report.get('assays',{}).get(assay['id'],{})
    if state.get('state') not in ('calculated','needs_review'):return dict(state='pending',issue=state.get('issue',''))
    wb=load_workbook(l.master,read_only=True,data_only=True)
    try:
        saved=lambda role:list(wb[sheet_name(assay,role)].values)
        data=dict(state='ready',issue=state.get('issue',''),summary=saved('Summary')[1:],
                  results=saved('Results')[1:],figures=[],figure_state='missing')
        if engine(assay['protocol']) in ('colorimetric','inhibition'):
            cal=saved('Calibration');data['calibration']={name:cal[row][9] for name,row in [('slope',2),('intercept',3),('r2',4)]}
    finally:wb.close()
    origin=report.get('origin',{})
    if origin.get('errors'):data['origin_issue']=True
    if not origin.get('project_saved') or origin.get('master_path')!=str(l.master):return data
    if not l.project.is_file() or report.get('project_sha256')!=file_hash(l.project):data['figure_state']='stale';return data
    base=(l.figures/assay['id']/'Origin').resolve();expected=report.get('outputs',{})
    titles={'calibration':'Calibrado','dose_response':'Curva de dosis','results':'Resultados por muestra'}
    for suffix,title in titles.items():
        for name in origin.get('exports',[]):
            path=(l.root/name).resolve()
            if not path.is_relative_to(base) or path.suffix.lower()!='.png' or not path.stem.endswith('_'+suffix):continue
            if not path.is_file() or expected.get(name)!=file_hash(path):data['figure_state']='stale';data['figures']=[];return data
            data['figures'].append((title,path));break
    data['figure_state']='ready' if data['figures'] else 'missing'
    return data

class FigurePreview(QLabel):
    activated=Signal()
    def __init__(self,path,parent=None):
        super().__init__(parent);self.path=Path(path);self.original=QPixmap(str(path));self.original.setDevicePixelRatio(1)
        self.setMinimumSize(240,210);self.setMaximumHeight(380);self.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self.setCursor(Qt.CursorShape.PointingHandCursor);self.setFocusPolicy(Qt.FocusPolicy.StrongFocus)
        self.setToolTip(t('Pulsa para ampliar la imagen original.'));self.setAccessibleName(t('Ampliar gráfica'))
        self.setStyleSheet('background:white;border-radius:8px')
    def resizeEvent(self,event):
        super().resizeEvent(event)
        if not self.original.isNull():
            ratio=self.devicePixelRatioF()
            preview=self.original.scaled(self.size()*ratio,Qt.AspectRatioMode.KeepAspectRatio,Qt.TransformationMode.SmoothTransformation)
            preview.setDevicePixelRatio(ratio);self.setPixmap(preview)
    def mouseReleaseEvent(self,event):
        if event.button()==Qt.MouseButton.LeftButton:self.activated.emit()
        super().mouseReleaseEvent(event)
    def keyPressEvent(self,event):
        if event.key() in (Qt.Key.Key_Return,Qt.Key.Key_Enter,Qt.Key.Key_Space):self.activated.emit()
        else:super().keyPressEvent(event)

